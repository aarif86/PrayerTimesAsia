#!/usr/bin/env python3
"""Writes the prayer alert lines from data/alert-lines.json into the web,
iPhone and Android code. Run after editing the JSON:
    python3 tools/build_alert_lines.py
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "data/alert-lines.json").read_text(encoding="utf-8"))
LANGS = ["en", "ms", "id"]
POOLS = ["fajr", "dhuhr", "asr", "maghrib", "isha", "jumuah", "any"]
HEADER = "Generated by tools/build_alert_lines.py from data/alert-lines.json. Do not edit by hand."

for lang in LANGS:
    for pool in POOLS:
        lines = DATA[lang][pool]
        want = len(DATA["en"][pool])
        assert len(lines) == want, f"{lang}.{pool} has {len(lines)} lines, English has {want}"
        for line in lines:
            assert ":" not in line and "—" not in line and "–" not in line and " - " not in line, f"no colons or dashes: {line}"
            assert pool == "any" and lang != "en" or "{p}" in line or pool == "any", f"missing {{p}}: {line}"
assert len(DATA["en"]["any"]) == 20, "the rotation below assumes 20 shared lines"
for pool in ["fajr", "dhuhr", "asr", "maghrib", "isha"]:
    assert len(DATA["en"][pool]) % 2 == 1, "an odd count keeps every line in the rotation"

def q(s, quote='"'):
    return quote + s.replace("\\", "\\\\").replace(quote, "\\" + quote) + quote

# Web
ts = [f"// {HEADER}", "", "export const ALERT_LINES = {"]
for lang in LANGS:
    ts.append(f"  {lang}: {{")
    for pool in POOLS:
        ts.append(f"    {pool}: [")
        ts += [f"      {q(l, chr(39))}," for l in DATA[lang][pool]]
        ts.append("    ],")
    ts.append("  },")
ts.append("} as const")
(ROOT / "web/src/core/alertLinesData.ts").write_text("\n".join(ts) + "\n", encoding="utf-8")

# iPhone
sw = [f"// {HEADER}", "", "extension AlertLines {", "    static let data: [RamadanContent.Lang: [String: [String]]] = ["]
for lang in LANGS:
    sw.append(f"        .{lang}: [")
    for pool in POOLS:
        sw.append(f"            {q(pool)}: [")
        sw += [f"                {q(l)}," for l in DATA[lang][pool]]
        sw.append("            ],")
    sw.append("        ],")
sw += ["    ]", "}"]
(ROOT / "ios/PrayerTimesAsia/Core/AlertLinesData.swift").write_text("\n".join(sw) + "\n", encoding="utf-8")

# Android
kt = ["package com.prayertimesasia.core", "", f"// {HEADER}", "", "internal object AlertLinesData {",
      "    val data: Map<RamadanContent.Lang, Map<String, List<String>>> = mapOf("]
for lang in LANGS:
    kt.append(f"        RamadanContent.Lang.{lang.upper()} to mapOf(")
    for pool in POOLS:
        kt.append(f"            {q(pool)} to listOf(")
        kt += [f"                {q(l).replace('$', '${\"$\"}')}," for l in DATA[lang][pool]]
        kt.append("            ),")
    kt.append("        ),")
kt += ["    )", "}"]
(ROOT / "android/core/src/main/kotlin/com/prayertimesasia/core/AlertLinesData.kt").write_text("\n".join(kt) + "\n", encoding="utf-8")
print("Wrote alert lines for", ", ".join(LANGS))
