#!/usr/bin/env python3
"""Writes the Ramadan page and card words from data/ramadan-words.json into the
web, iPhone and Android code. Run after editing the JSON:
    python3 tools/build_ramadan_words.py
    python3 tools/build_ramadan_words.py --check   (fails if the code is out of date)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "data/ramadan-words.json").read_text(encoding="utf-8"))
LANGS = ["en", "ms", "id"]
HEADER = "Generated by tools/build_ramadan_words.py from data/ramadan-words.json. Do not edit by hand."
HOLE = re.compile(r"\{([a-z]+)\}")

# Every key in every language, the same {holes}, and plain words only.
keys = [k for k in DATA["en"] if not k.endswith("_one")]
for lang in LANGS:
    words = DATA[lang]
    missing = [k for k in keys if k not in words]
    assert not missing, f"{lang} is missing {missing}"
    extra = [k for k in words if k not in DATA["en"] and not (k.endswith("_one") and k[:-4] in words)]
    assert not extra, f"{lang} has keys English doesn't: {extra}"
    for k, line in words.items():
        base = k[:-4] if k.endswith("_one") else k
        assert set(HOLE.findall(line)) == set(HOLE.findall(DATA["en"][base])), f"{lang}.{k} has other {{holes}} than English"
        assert line == line.strip(), f"{lang}.{k} starts or ends with a space"
        assert ":" not in line and "—" not in line and "–" not in line and "-" not in line, f"no colons or dashes: {lang}.{k}"
        if lang == "ms":
            assert not re.search(r"\blah\b", line, re.I), f"no lah: {k}"
        assert line or k.startswith("letter_"), f"{lang}.{k} is empty"


def q(s, quote='"'):
    return quote + s.replace("\\", "\\\\").replace(quote, "\\" + quote) + quote


def kotlin(s):
    return q(s).replace("$", "${'$'}")


all_keys = list(DATA["en"].keys())

# Web
ts = [f"// {HEADER}", "", "export const RAMADAN_WORDS_DATA = {"]
for lang in LANGS:
    ts.append(f"  {lang}: {{")
    ts += [f"    {k}: {q(v, chr(39))}," for k, v in DATA[lang].items()]
    ts.append("  },")
ts += ["} as const", "", "export type RamadanWordKey = Exclude<keyof typeof RAMADAN_WORDS_DATA.en, `${string}_one`>", ""]
web = "\n".join(ts)

# iPhone
sw = [f"// {HEADER}", "", "/// A word on the Ramadan page or card. The text is in RamadanWords.data.", "enum RamadanWordKey: String, CaseIterable, Sendable {"]
sw += [f"    case {k}" for k in keys]
sw += ["}", "", "extension RamadanWords {", "    static let data: [RamadanContent.Lang: [String: String]] = ["]
for lang in LANGS:
    sw.append(f"        .{lang}: [")
    sw += [f"            {q(k)}: {q(v)}," for k, v in DATA[lang].items()]
    sw.append("        ],")
sw += ["    ]", "}", ""]
swift = "\n".join(sw)

# Android
kt = ["package com.prayertimesasia.core", "", f"// {HEADER}", "", "/** A word on the Ramadan page or card. The text is in [RamadanWords]. */",
      "@Suppress(\"EnumEntryName\")", "enum class RamadanWordKey {"]
kt += [f"    {k}," for k in keys]
kt += ["}", "", "internal object RamadanWordsData {", "    val data: Map<RamadanContent.Lang, Map<String, String>> = mapOf("]
for lang in LANGS:
    kt.append(f"        RamadanContent.Lang.{lang.upper()} to mapOf(")
    kt += [f"            {q(k)} to {kotlin(v)}," for k, v in DATA[lang].items()]
    kt.append("        ),")
kt += ["    )", "}", ""]
android = "\n".join(kt)

OUT = {
    "web/src/core/ramadanWordsData.ts": web,
    "ios/PrayerTimesAsia/Core/RamadanWordsData.swift": swift,
    "android/core/src/main/kotlin/com/prayertimesasia/core/RamadanWordsData.kt": android,
}

if "--check" in sys.argv:
    stale = [p for p, text in OUT.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text]
    if stale:
        sys.exit(f"Out of date, run python3 tools/build_ramadan_words.py: {', '.join(stale)}")
    print(f"Ramadan words OK, {len(keys)} lines in {len(LANGS)} languages")
else:
    for p, text in OUT.items():
        (ROOT / p).write_text(text, encoding="utf-8")
    print(f"Wrote {len(keys)} Ramadan lines in {len(LANGS)} languages")
