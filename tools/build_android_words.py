#!/usr/bin/env python3
"""Writes the shared app words (data/app-words/en.json, ms.json, id.json) into
Android string resources, so the list stays the single source:

    android/app/src/main/res/values/app_words.xml      (English)
    android/app/src/main/res/values-ms/app_words.xml   (Malay)
    android/app/src/main/res/values-in/app_words.xml   (Indonesian; Android's folder name for id)

    python3 tools/build_android_words.py           (write the files)
    python3 tools/build_android_words.py --check   (fails if they are out of date)

A key like settings.alerts becomes the resource R.string.settings_alerts. The
{holes} stay as they are; the app fills them in (ui/components/AppWords.kt).
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "data/app-words"
RES = ROOT / "android/app/src/main/res"
FOLDERS = {"en": "values", "ms": "values-ms", "id": "values-in"}
HEADER = "Generated by tools/build_android_words.py from data/app-words. Do not edit by hand."
KEY = re.compile(r"^[a-z][a-zA-Z0-9]*(\.[a-z][a-zA-Z0-9]*)+(_one)?$")

words = {lang: json.loads((DIR / f"{lang}.json").read_text(encoding="utf-8")) for lang in FOLDERS}


def name(key: str) -> str:
    assert KEY.match(key), f"odd key {key!r}"
    return key.replace(".", "_")


def escape(s: str) -> str:
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s


def xml(lang: str) -> str:
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->",
           '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,Typos">']
    for k in words["en"]:
        out.append(f'    <string name="{name(k)}" formatted="false">{escape(words[lang][k])}</string>')
    out += ["</resources>", ""]
    return "\n".join(out)


CORE = ROOT / "android/core/src/main/kotlin/com/prayertimesasia/core/NotifyWordsData.kt"
NOTIFY = [k for k in words["en"] if k.startswith(("notify.", "phone.notify."))]


def kt_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")


def notify_kt() -> str:
    """The alert lines, for the alert planner (it has no Android Context, so it cannot read string resources)."""
    out = ["package com.prayertimesasia.core", "", f"// {HEADER}", "", "internal object NotifyWordsData {",
           "    val data: Map<RamadanContent.Lang, Map<String, String>> = mapOf("]
    for lang, tag in (("en", "EN"), ("ms", "MS"), ("id", "ID")):
        out.append(f"        RamadanContent.Lang.{tag} to mapOf(")
        for k in NOTIFY:
            out.append(f'            "{k}" to "{kt_escape(words[lang][k])}",')
        out.append("        ),")
    out += ["    )", "}", ""]
    return "\n".join(out)


names = [name(k) for k in words["en"]]
assert len(names) == len(set(names)), "two keys make the same resource name"
OUT = {RES / folder / "app_words.xml": xml(lang) for lang, folder in FOLDERS.items()}
OUT[CORE] = notify_kt()

if "--check" in sys.argv:
    stale = [str(p.relative_to(ROOT)) for p, text in OUT.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if stale:
        sys.exit(f"Out of date, run python3 tools/build_android_words.py: {', '.join(stale)}")
    print(f"Android app words OK, {len(names)} lines in {len(OUT)} languages")
else:
    for p, text in OUT.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"Wrote {len(names)} Android lines in {len(OUT)} languages")
