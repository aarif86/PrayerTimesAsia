"""Regenerates PrayerTimesAsia/Core/JakimZones.swift from tools/jakim_reference_points.json.

The JSON holds one reference point per district (largest polygon part, plus
islands) with its JAKIM zone, derived from the district-to-zone mapping in
github.com/mptwaktusolat/malaysia.geojson (malaysia.district-jakim.geojson).
"""
import collections
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(root, 'tools', 'jakim_reference_points.json')))
zones = collections.OrderedDict()
for code, name, lat, lng in rows:
    zones.setdefault(code, []).append(name)

out = ['// Generated by tools/gen_jakim_zones.py from tools/jakim_reference_points.json - do not edit.',
       '// Reference points: one per district (largest polygon part, plus islands), derived from the',
       '// district-to-zone mapping in github.com/mptwaktusolat/malaysia.geojson.',
       '', 'enum JakimZones {',
       '    struct Zone: Identifiable, Hashable, Sendable {', '        let id: String', '        let areas: String', '    }',
       '', '    static let zones: [Zone] = [']
for code, names in zones.items():
    areas = ', '.join(dict.fromkeys(n.replace('W.P. ', '') for n in names))
    out.append(f'        Zone(id: "{code}", areas: "{areas}"),')
out += ['    ]', '', '    /// (zone, latitude, longitude)', '    static let points: [(String, Double, Double)] = [']
for code, name, lat, lng in rows:
    out.append(f'        ("{code}", {lat}, {lng}),')
out += ['    ]', '}']
open(os.path.join(root, 'PrayerTimesAsia', 'Core', 'JakimZones.swift'), 'w').write('\n'.join(out) + '\n')
