#!/usr/bin/env python3
"""Writes the community cards from data/community-cards.json into the web,
iPhone and Android code, after checking every card against the rules in
docs/community-cards.md. Run after editing the JSON:
    python3 tools/build_community_cards.py
    python3 tools/build_community_cards.py --check   (fails if the code is out of date)
"""
import datetime, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "data/community-cards.json").read_text(encoding="utf-8"))
CODES = {c["code"] for c in json.loads((ROOT / "data/countries.json").read_text(encoding="utf-8"))["countries"]} | {"SG", "MY", "ID", "BN"}
HEADER = "Generated by tools/build_community_cards.py from data/community-cards.json. Do not edit by hand."
KINDS = {"ours", "sponsor"}
ICONS = {"kaaba", "globe", "shop", "heart"}

cards = DATA["cards"]
seen = set()
for c in cards:
    cid = c["id"]
    assert re.fullmatch(r"[a-z0-9]+", cid), f"id is lower case letters and digits only: {cid}"
    assert cid not in seen, f"two cards are called {cid}"
    seen.add(cid)
    assert c["kind"] in KINDS, f"{cid}: kind is ours or sponsor"
    assert c.get("icon", "globe") in ICONS, f"{cid}: icon is one of {sorted(ICONS)}"
    assert c["countries"], f"{cid}: needs at least one country, or *"
    for code in c["countries"]:
        assert code == "*" or code in CODES, f"{cid}: unknown country {code}"
    assert c["url"].startswith("https://"), f"{cid}: url must start with https://"
    for field in ("title", "subtitle", "site"):
        text = c[field]
        assert text and text == text.strip(), f"{cid}.{field} is empty or has spaces at the ends"
        assert ":" not in text and "—" not in text and "–" not in text and " - " not in text, f"no colons or dashes: {cid}.{field}"
    assert len(c["title"]) <= 28, f"{cid}: title is over 28 letters, it won't fit on one line"
    assert len(c["subtitle"]) <= 80, f"{cid}: subtitle is over 80 letters"
    for d in ("from", "until"):
        if c.get(d):
            datetime.date.fromisoformat(c[d])
    if c["kind"] == "sponsor":
        # A paid card needs a name on it: who approved it, and when.
        assert c.get("approvedBy") and c.get("approvedOn"), f"{cid}: a sponsor card needs approvedBy and approvedOn"
        datetime.date.fromisoformat(c["approvedOn"])
        assert c.get("until"), f"{cid}: a sponsor card needs an until date"


def q(s, quote='"'):
    return quote + s.replace("\\", "\\\\").replace(quote, "\\" + quote) + quote


def kotlin(s):
    return q(s).replace("$", "${'$'}")


def opt(v, f):
    return f(v) if v else None


# Web
ts = [f"// {HEADER}", "", "import type { CommunityCard } from './communityCards'", "", "export const COMMUNITY_CARDS: CommunityCard[] = ["]
for c in cards:
    parts = [f"id: {q(c['id'], chr(39))}", f"kind: {q(c['kind'], chr(39))}",
             "countries: [" + ", ".join(q(x, chr(39)) for x in c["countries"]) + "]",
             f"title: {q(c['title'], chr(39))}", f"subtitle: {q(c['subtitle'], chr(39))}",
             f"site: {q(c['site'], chr(39))}", f"url: {q(c['url'], chr(39))}", f"icon: {q(c.get('icon', 'globe'), chr(39))}"]
    if c.get("from"): parts.append(f"from: {q(c['from'], chr(39))}")
    if c.get("until"): parts.append(f"until: {q(c['until'], chr(39))}")
    ts.append("  { " + ", ".join(parts) + " },")
ts += ["]", ""]
web = "\n".join(ts)

# iPhone
sw = [f"// {HEADER}", "", "extension CommunityCard {", "    static let all: [CommunityCard] = ["]
for c in cards:
    sw.append(
        f"        CommunityCard(id: {q(c['id'])}, kind: .{c['kind']}, countries: [{', '.join(q(x) for x in c['countries'])}], "
        f"title: {q(c['title'])}, subtitle: {q(c['subtitle'])}, site: {q(c['site'])}, link: {q(c['url'])}, "
        f"icon: .{c.get('icon', 'globe')}, from: {q(c['from']) if c.get('from') else 'nil'}, until: {q(c['until']) if c.get('until') else 'nil'}),")
sw += ["    ]", "}", ""]
swift = "\n".join(sw)

# Android
kt = ["package com.prayertimesasia.core", "", f"// {HEADER}", "", "internal object CommunityCardsData {", "    val all: List<CommunityCard> = listOf("]
for c in cards:
    kt.append(
        f"        CommunityCard({kotlin(c['id'])}, CommunityCard.Kind.{c['kind'].upper()}, listOf({', '.join(kotlin(x) for x in c['countries'])}), "
        f"{kotlin(c['title'])}, {kotlin(c['subtitle'])}, {kotlin(c['site'])}, {kotlin(c['url'])}, "
        f"CommunityCard.Icon.{c.get('icon', 'globe').upper()}, {kotlin(c['from']) if c.get('from') else 'null'}, {kotlin(c['until']) if c.get('until') else 'null'}),")
kt += ["    )", "}", ""]
android = "\n".join(kt)

OUT = {
    "web/src/core/communityCardsData.ts": web,
    "ios/PrayerTimesAsia/Core/CommunityCardsData.swift": swift,
    "android/core/src/main/kotlin/com/prayertimesasia/core/CommunityCardsData.kt": android,
}

if "--check" in sys.argv:
    stale = [p for p, text in OUT.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text]
    if stale:
        sys.exit(f"Out of date, run python3 tools/build_community_cards.py: {', '.join(stale)}")
    print(f"Community cards OK, {len(cards)} cards")
else:
    for p, text in OUT.items():
        (ROOT / p).write_text(text, encoding="utf-8")
    print(f"Wrote {len(cards)} community cards")
