#!/usr/bin/env python3
"""Writes the shared app words (data/app-words/en.json, ms.json, id.json) into
the iPhone code, so the list stays the single source:

    ios/PrayerTimesAsia/Core/AppWordsData.swift

    python3 tools/build_ios_words.py           (write the file)
    python3 tools/build_ios_words.py --check   (fails if it is out of date)

The app reads a line with AppWords.text("settings.alerts", lang) and fills the
{holes} in. Run tools/check_app_words.py first, it checks the list itself.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "data/app-words"
LANGS = ["en", "ms", "id"]
HEADER = "Generated by tools/build_ios_words.py from data/app-words. Do not edit by hand."
OUT = ROOT / "ios/PrayerTimesAsia/Core/AppWordsData.swift"

words = {lang: json.loads((DIR / f"{lang}.json").read_text(encoding="utf-8")) for lang in LANGS}


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


lines = [f"// {HEADER}", "", "extension AppWords {"]
for lang in LANGS:
    lines.append(f"    static let {lang}Lines: [String: String] = [")
    lines += [f"        {q(k)}: {q(v)}," for k, v in words[lang].items()]
    lines.append("    ]")
    lines.append("")
lines[-1:] = ["}", ""]
text = "\n".join(lines)

if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        sys.exit("Out of date, run python3 tools/build_ios_words.py: ios/PrayerTimesAsia/Core/AppWordsData.swift")
    print(f"iPhone app words OK, {len(words['en'])} lines in {len(LANGS)} languages")
else:
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {len(words['en'])} iPhone lines in {len(LANGS)} languages")
