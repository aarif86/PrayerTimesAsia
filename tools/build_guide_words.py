#!/usr/bin/env python3
"""Writes the quick guide words (the swipe cards new users see once) from
data/guide-words.json into the web, iPhone and Android code. Run after editing the JSON:
    python3 tools/build_guide_words.py
    python3 tools/build_guide_words.py --check   (fails if the code is out of date)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "data/guide-words.json").read_text(encoding="utf-8"))
LANGS = ["en", "ms", "id"]
CARDS = DATA["cards"]
HEADER = "Generated by tools/build_guide_words.py from data/guide-words.json. Do not edit by hand."
SHOTS = json.loads((ROOT / "data/guide-shots.json").read_text(encoding="utf-8"))
STEPS = DATA["steps"]
HOLE = re.compile(r"\{([a-z]+)\}")

keys = list(DATA["en"].keys())
for c in CARDS:
    assert f"{c}_title" in keys and f"{c}_body" in keys, f"card {c} needs a title and a body"
# Each card shows a little phone that steps through real app screens: [screen, words, tap or not].
assert list(STEPS.keys()) == CARDS, "steps must list every card, in card order"
for c, steps in STEPS.items():
    for shot, say, tap in steps:
        assert shot in SHOTS, f"{c}: no box for screen {shot}, run web/scripts/guide-shots.mjs"
        assert (ROOT / f"web/src/assets/guide/steps/{shot}.webp").exists(), f"{c}: no picture for {shot}"
        assert say in keys, f"{c}: no words for {say}"
        assert tap in (0, 1)
for lang in LANGS:
    words = DATA[lang]
    assert list(words.keys()) == keys, f"{lang} must have the same keys as English, in the same order"
    for k, line in words.items():
        assert line and line == line.strip(), f"{lang}.{k} is empty or has spaces around it"
        assert set(HOLE.findall(line)) == set(HOLE.findall(DATA["en"][k])), f"{lang}.{k} has other {{holes}} than English"
        # Public copy rule: no colons and no dashes (a hyphen inside a word, like mana-mana, is fine).
        assert ":" not in line and "—" not in line and "–" not in line and " - " not in line, f"no colons or dashes: {lang}.{k}"
        if lang == "ms":
            assert not re.search(r"\blah\b", line, re.I), f"no lah: {k}"


def q(s, quote='"'):
    return quote + s.replace("\\", "\\\\").replace(quote, "\\" + quote) + quote


def kotlin(s):
    return q(s).replace("$", "${'$'}")


# Web
ts = [f"// {HEADER}", "", f"export const GUIDE_CARD_IDS = [{', '.join(q(c, chr(39)) for c in CARDS)}] as const", "",
      "export const GUIDE_WORDS_DATA = {"]
for lang in LANGS:
    ts.append(f"  {lang}: {{")
    ts += [f"    {k}: {q(v, chr(39))}," for k, v in DATA[lang].items()]
    ts.append("  },")
ts += ["} as const", "", "export type GuideWordKey = keyof typeof GUIDE_WORDS_DATA.en", "",
       "/** Each card's little phone: the app screen, where the finger points (fractions of the screen), the words, and whether it taps. */",
       "export const GUIDE_STEPS_DATA = {"]
for c, steps in STEPS.items():
    ts.append(f"  {c}: [")
    for shot, say, tap in steps:
        b = SHOTS[shot]
        ts.append(f"    {{ shot: '{shot}', x: {b['x']}, y: {b['y']}, w: {b['w']}, h: {b['h']}, say: '{say}', tap: {'true' if tap else 'false'} }},")
    ts.append("  ],")
ts += ["} as const", ""]
web = "\n".join(ts)

# iPhone
sw = [f"// {HEADER}", "", "extension GuideWords {", f"    static let cards: [String] = [{', '.join(q(c) for c in CARDS)}]", "",
      "    static let data: [RamadanContent.Lang: [String: String]] = ["]
for lang in LANGS:
    sw.append(f"        .{lang}: [")
    sw += [f"            {q(k)}: {q(v)}," for k, v in DATA[lang].items()]
    sw.append("        ],")
sw += ["    ]", "",
       "    /// Each card's little phone: the app screen, where the finger points (fractions of the screen), the words, and whether it taps.",
       "    static let steps: [String: [Step]] = ["]
for c, steps in STEPS.items():
    sw.append(f"        {q(c)}: [")
    for shot, say, tap in steps:
        b = SHOTS[shot]
        sw.append(f"            Step(shot: {q(shot)}, x: {b['x']}, y: {b['y']}, w: {b['w']}, h: {b['h']}, say: {q(say)}, tap: {'true' if tap else 'false'}),")
    sw.append("        ],")
sw += ["    ]", "}", ""]
swift = "\n".join(sw)

# Android
kt = ["package com.prayertimesasia.core", "", f"// {HEADER}", "", "internal object GuideWordsData {",
      f"    val cards: List<String> = listOf({', '.join(q(c) for c in CARDS)})", "",
      "    val data: Map<RamadanContent.Lang, Map<String, String>> = mapOf("]
for lang in LANGS:
    kt.append(f"        RamadanContent.Lang.{lang.upper()} to mapOf(")
    kt += [f"            {q(k)} to {kotlin(v)}," for k, v in DATA[lang].items()]
    kt.append("        ),")
kt += ["    )", "",
       "    /** Each card's little phone: the app screen, where the finger points (fractions of the screen), the words, and whether it taps. */",
       "    val steps: Map<String, List<GuideStep>> = mapOf("]
for c, steps in STEPS.items():
    kt.append(f"        {q(c)} to listOf(")
    for shot, say, tap in steps:
        b = SHOTS[shot]
        kt.append(f"            GuideStep({q(shot)}, {b['x']}f, {b['y']}f, {b['w']}f, {b['h']}f, {q(say)}, {'true' if tap else 'false'}),")
    kt.append("        ),")
kt += ["    )", "}", ""]
android = "\n".join(kt)

OUT = {
    "web/src/core/guideWordsData.ts": web,
    "ios/PrayerTimesAsia/Core/GuideWordsData.swift": swift,
    "android/core/src/main/kotlin/com/prayertimesasia/core/GuideWordsData.kt": android,
}

# The phone pictures: web keeps the .webp files; iPhone gets a .jpg asset each and Android a drawable.
SHOT_NAMES = sorted({shot for steps in STEPS.values() for shot, _, _ in steps})
ASSETS = ROOT / "ios/PrayerTimesAsia/Resources/Assets.xcassets"
DRAWABLES = ROOT / "android/app/src/main/res/drawable-nodpi"


def ios_set(shot):
    return ASSETS / f"Guide-step-{shot}.imageset"


def android_file(shot):
    return DRAWABLES / f"guide_step_{shot.lower()}.webp"


def write_images():
    from PIL import Image
    import shutil
    for old in ASSETS.glob("Guide-step-*.imageset"):
        if old.name[len("Guide-step-"):-len(".imageset")] not in SHOT_NAMES:
            shutil.rmtree(old)
    for old in DRAWABLES.glob("guide_step_*.webp"):
        if old.stem[len("guide_step_"):] not in {s.lower() for s in SHOT_NAMES}:
            old.unlink()
    for shot in SHOT_NAMES:
        src = ROOT / f"web/src/assets/guide/steps/{shot}.webp"
        d = ios_set(shot)
        d.mkdir(exist_ok=True)
        Image.open(src).convert("RGB").save(d / f"{shot}.jpg", quality=80)
        (d / "Contents.json").write_text(json.dumps({"images": [{"filename": f"{shot}.jpg", "idiom": "universal"}],
                                                     "info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
        shutil.copyfile(src, android_file(shot))


if "--check" in sys.argv:
    missing = [str(p) for shot in SHOT_NAMES for p in (ios_set(shot) / f"{shot}.jpg", android_file(shot)) if not p.exists()]
    if missing:
        sys.exit(f"Guide pictures missing, run python3 tools/build_guide_words.py: {', '.join(missing)}")
    stale = [p for p, text in OUT.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text]
    if stale:
        sys.exit(f"Out of date, run python3 tools/build_guide_words.py: {', '.join(stale)}")
    print(f"Guide words OK, {len(CARDS)} cards in {len(LANGS)} languages")
else:
    for p, text in OUT.items():
        (ROOT / p).write_text(text, encoding="utf-8")
    write_images()
    print(f"Wrote {len(CARDS)} guide cards in {len(LANGS)} languages")
