"""Regenerates the country tables of all three apps from data/countries.json.

    python3 tools/gen_countries.py

Writes docs/worldwide-times.md, web/src/core/countries.ts, ios/PrayerTimesAsia/Core/Countries.swift and
android/core/src/main/kotlin/com/prayertimesasia/core/Countries.kt. Edit the
JSON, never the generated files. CI runs this with --check.
"""
import json
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(root, 'data', 'countries.json'), encoding='utf-8'))
countries = data['countries']

METHODS = {'muis', 'jakim', 'kemenag', 'sea', 'mwl', 'karachi', 'ummalqura', 'dubai', 'qatar', 'kuwait', 'diyanet',
           'tehran', 'egyptian', 'isna', 'moonsighting', 'uoif', 'russia', 'algeria', 'tunisia', 'morocco', 'jordan'}
SOURCES = {'table', 'authority', 'standard'}
RULES = {None, 'angle', 'seventh', 'middle'}
NAMING = {'international', 'malay', 'indonesian', 'turkish', 'southAsian'}
problems = []
seen_zones = {}
for c in countries:
    if c['method'] not in METHODS: problems.append(f"{c['code']}: unknown method {c['method']}")
    if c['source'] not in SOURCES: problems.append(f"{c['code']}: unknown source {c['source']}")
    if c['source'] != 'standard' and not c.get('authority'): problems.append(f"{c['code']}: {c['source']} needs an authority")
    if c.get('highLatitude') not in RULES: problems.append(f"{c['code']}: unknown highLatitude {c.get('highLatitude')}")
    if c['naming'] not in NAMING: problems.append(f"{c['code']}: unknown naming {c['naming']}")
    for text in (c.get('authority'), c.get('note')):
        if text and (':' in text or ' - ' in text or '–' in text or '—' in text):
            problems.append(f"{c['code']}: no colons or dashes in shown text: {text!r}")
    for z in c['zones']:
        if z in seen_zones: problems.append(f"{z} is listed for both {seen_zones[z]} and {c['code']}")
        seen_zones[z] = c['code']
    for city in c['cities']:
        if len(city) < 5 and not c['zones']: problems.append(f"{c['code']} {city[0]}: needs a time zone")
if problems:
    sys.exit('\n'.join(problems))


def q(s):
    return json.dumps(s, ensure_ascii=False)


def city_zone(c, city):
    return city[4] if len(city) > 4 else c['zones'][0]


HEADER = '// Generated by tools/gen_countries.py from data/countries.json. Do not edit.'

# ---------- web ----------
ts = [HEADER, "import type { NamingStyle, AsrSchool } from './prayer'", '',
      "export type TimesSource = 'table' | 'authority' | 'standard'",
      "export type CountryHighLatitude = 'angle' | 'seventh' | 'middle'", '',
      'export interface CountryRow {', '  code: string', '  name: string', '  methodID: string', '  asr: AsrSchool',
      '  naming: NamingStyle', '  source: TimesSource', '  authority?: string', '  note?: string',
      '  highLatitude?: CountryHighLatitude', '}', '',
      'export const COUNTRY_ROWS: CountryRow[] = [']
TS_NAMING = {'international': 'arabic'}
for c in countries:
    parts = [f"code: {q(c['code'])}", f"name: {q(c['name'])}", f"methodID: {q(c['method'])}", f"asr: {q(c['asr'])}",
             f"naming: {q(TS_NAMING.get(c['naming'], c['naming']))}", f"source: {q(c['source'])}"]
    if c.get('authority'): parts.append(f"authority: {q(c['authority'])}")
    if c.get('note'): parts.append(f"note: {q(c['note'])}")
    if c.get('highLatitude'): parts.append(f"highLatitude: {q(c['highLatitude'])}")
    ts.append('  { ' + ', '.join(parts) + ' },')
ts += [']', '', '/** Time zone to country, for an offline guess. */', 'export const TZ_COUNTRY: Record<string, string> = {']
for c in countries:
    for z in c['zones']:
        ts.append(f"  {q(z)}: {q(c['code'])},")
ts += ['}', '', '/** Cities outside the hand-kept Asian list: [name, region, country, latitude, longitude, time zone]. */',
       'export const WORLD_CITIES: [string, string, string, number, number, string][] = [']
for c in countries:
    for city in c['cities']:
        ts.append(f"  [{q(city[0])}, {q(city[1])}, {q(c['code'])}, {city[2]}, {city[3]}, {q(city_zone(c, city))}],")
ts += [']', '']

# ---------- iOS ----------
SW_NAMING = {'international': '.international', 'malay': '.malay', 'indonesian': '.indonesian', 'turkish': '.turkish',
             'southAsian': '.southAsian'}
sw = [HEADER, 'import Foundation', '', 'enum Countries {', '    static let profiles: [CountryProfile] = [']
for c in countries:
    args = [f"code: {q(c['code'])}", f"name: {q(c['name'])}", f"methodID: {q(c['method'])}",
            f"asr: .{c['asr']}", f"naming: {SW_NAMING[c['naming']]}", f"source: .{c['source']}",
            f"authority: {q(c['authority']) if c.get('authority') else 'nil'}",
            f"note: {q(c['note']) if c.get('note') else 'nil'}",
            f"highLatitude: {'.' + c['highLatitude'] if c.get('highLatitude') else 'nil'}"]
    sw.append('        CountryProfile(' + ', '.join(args) + '),')
sw += ['    ]', '', '    static let timeZoneCountries: [String: String] = [']
for c in countries:
    for z in c['zones']:
        sw.append(f"        {q(z)}: {q(c['code'])},")
sw += ['    ]', '}', '']

# ---------- Android ----------
KT_NAMING = {'international': 'INTERNATIONAL', 'malay': 'MALAY', 'indonesian': 'INDONESIAN', 'turkish': 'TURKISH',
             'southAsian': 'SOUTH_ASIAN'}
KT_RULE = {'angle': 'ANGLE', 'seventh': 'SEVENTH', 'middle': 'MIDDLE'}


def kq(s):
    return q(s).replace('$', '\\$')


kt = [HEADER, 'package com.prayertimesasia.core', '', 'object Countries {', '    val profiles: List<CountryProfile> = listOf(']
for c in countries:
    args = [kq(c['code']), kq(c['name']), kq(c['method']), f"AsrSchool.{c['asr'].upper()}",
            f"NamingStyle.{KT_NAMING[c['naming']]}", f"TimesSource.{c['source'].upper()}",
            kq(c['authority']) if c.get('authority') else 'null', kq(c['note']) if c.get('note') else 'null',
            f"HighLatitudeRule.{KT_RULE[c['highLatitude']]}" if c.get('highLatitude') else 'null']
    kt.append('        CountryProfile(' + ', '.join(args) + '),')
kt += ['    )', '', '    val timeZoneCountries: Map<String, String> = mapOf(']
for c in countries:
    for z in c['zones']:
        kt.append(f"        {kq(z)} to {kq(c['code'])},")
kt += ['    )', '', '    /** Cities outside the hand-kept Asian list. */', '    val worldCities: List<Cities.City> = listOf(']
for c in countries:
    for city in c['cities']:
        kt.append(f"        Cities.City({kq(city[0])}, {kq(city[1])}, {kq(c['code'])}, {city[2]}, {city[3]}, {kq(city_zone(c, city))}),")
kt += ['    )', '}', '']

METHOD_NAMES = {'muis': 'MUIS', 'jakim': 'JAKIM', 'kemenag': 'Kemenag', 'sea': 'Southeast Asia 20°/18°', 'mwl': 'Muslim World League',
                'karachi': 'Karachi', 'ummalqura': 'Umm al-Qura', 'dubai': 'UAE', 'qatar': 'Qatar', 'kuwait': 'Kuwait',
                'diyanet': 'Diyanet', 'tehran': 'Tehran', 'egyptian': 'Egyptian', 'isna': 'ISNA', 'moonsighting': 'Moonsighting Committee',
                'uoif': 'France 12°', 'russia': 'Muslims of Russia', 'algeria': 'Algeria', 'tunisia': 'Tunisia', 'morocco': 'Morocco',
                'jordan': 'Jordan'}
SOURCE_WORDS = {'table': 'Official timetable, downloaded', 'authority': "Authority's own method", 'standard': 'Standard method'}
md = ['# Prayer times around the world', '',
      '*Generated by `tools/gen_countries.py` from `data/countries.json`. Edit the JSON, then run the script.*', '',
      'The rule: the local official or state religious authority comes first. Where it publishes a timetable the app can download,',
      'the app shows that timetable (Singapore, Malaysia, Indonesia today). Where it publishes its method, the app works the',
      'times out on the phone with that method, so they work offline. Only where no authority\'s times can be used does the app',
      'fall back to a standard method, and then it says so on the Prayer screen, in Settings and on the Source page.', '',
      'Far from the equator in summer the sky never gets fully dark. For those countries the app uses a twilight rule',
      '(a share of the night based on the angle), and in the UK and Ireland the Moonsighting Committee\'s seasonal rule.', '',
      'A nearby masjid\'s own timetable (data/mosques.json) still comes before all of this when it has been sent in and checked.', '',
      '| Country | Whose times | Method | Asr | Summer nights | Note |', '|---|---|---|---|---|---|']
for c in countries:
    md.append('| ' + ' | '.join([
        c['name'], (c.get('authority') or SOURCE_WORDS[c['source']]) + ('' if c['source'] == 'standard' else f" ({SOURCE_WORDS[c['source']].lower()})"),
        METHOD_NAMES[c['method']], 'Hanafi' if c['asr'] == 'hanafi' else "Shafi'i", c.get('highLatitude') or "method's own",
        (c.get('note') or '').replace('|', '/')]) + ' |')
md.append('')

outputs = {
    os.path.join(root, 'docs', 'worldwide-times.md'): '\n'.join(md),
    os.path.join(root, 'web', 'src', 'core', 'countries.ts'): '\n'.join(ts),
    os.path.join(root, 'ios', 'PrayerTimesAsia', 'Core', 'Countries.swift'): '\n'.join(sw),
    os.path.join(root, 'android', 'core', 'src', 'main', 'kotlin', 'com', 'prayertimesasia', 'core', 'Countries.kt'): '\n'.join(kt),
}
check = '--check' in sys.argv
stale = []
for path, text in outputs.items():
    if check:
        if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
            stale.append(os.path.relpath(path, root))
    else:
        open(path, 'w', encoding='utf-8').write(text)
if stale:
    sys.exit('Out of date, run python3 tools/gen_countries.py: ' + ', '.join(stale))
print(f'{len(countries)} countries, {sum(len(c["cities"]) for c in countries)} world cities')
