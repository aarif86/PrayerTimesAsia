#!/usr/bin/env python3
"""Turns data/friday-sg.json and data/eid-sg.json into code for the phones.

    python3 tools/gen_masjid_extras.py          write the files
    python3 tools/gen_masjid_extras.py --check  fail if they are out of date

Writes android/core/.../MasjidExtrasData.kt and ios/PrayerTimesAsia/Core/MasjidExtrasData.swift.
The web app reads the JSON files directly. Edit the JSON, never the generated files.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KT = os.path.join(ROOT, "android/core/src/main/kotlin/com/prayertimesasia/core/MasjidExtrasData.kt")
SW = os.path.join(ROOT, "ios/PrayerTimesAsia/Core/MasjidExtrasData.swift")


def q(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def qs(s):
    return json.dumps(s, ensure_ascii=False)


def opt_num(v, swift=False):
    return "nil" if v is None and swift else ("null" if v is None else repr(float(v)))


def build():
    fri = json.load(open(os.path.join(ROOT, "data/friday-sg.json")))
    eid = json.load(open(os.path.join(ROOT, "data/eid-sg.json")))
    kt = ["// Generated by tools/gen_masjid_extras.py from data/friday-sg.json and data/eid-sg.json. Do not edit.",
          "package com.prayertimesasia.core", "", "internal object MasjidExtrasData {",
          f"    const val FRIDAY_SOURCE_URL = {q(fri['sourceUrl'])}",
          f"    const val FRIDAY_SOURCE_UPDATED = {q(fri['sourceUpdated'])}",
          f"    const val FRIDAY_SECOND_FROM = {q(fri['secondSessionFrom'])}",
          "    val friday = listOf("]
    sw = ["// Generated by tools/gen_masjid_extras.py from data/friday-sg.json and data/eid-sg.json. Do not edit.",
          "import Foundation", "", "enum MasjidExtrasData {",
          f"    static let fridaySourceURL = {qs(fri['sourceUrl'])}",
          f"    static let fridaySourceUpdated = {qs(fri['sourceUpdated'])}",
          f"    static let fridaySecondFrom = {qs(fri['secondSessionFrom'])}",
          "    static let friday: [FridayMosque] = ["]
    for m in fri["mosques"]:
        kt.append(f"        FridayMosque({q(m['name'])}, {q(m['district'])}, {m['lat']}, {m['lng']}, {str(m['womenSession2']).lower()}),")
        sw.append(f"        FridayMosque(name: {qs(m['name'])}, district: {qs(m['district'])}, lat: {m['lat']}, lng: {m['lng']}, womenSession2: {str(m['womenSession2']).lower()}),")
    kt.append("    )")
    sw.append("    ]")
    kt.append("    val eid = listOf<EidEvent>(")
    sw.append("    static let eid: [EidEvent] = [")
    for e in eid["events"]:
        kms, sms = [], []
        for m in e["mosques"]:
            ks = ", ".join(f"EidSession({q(x['time'])}, {q(x['khutbah']) if x.get('khutbah') else 'null'}, {str(bool(x.get('women'))).lower()})" for x in m["sessions"])
            ss = ", ".join(f"EidSession(time: {qs(s['time'])}, khutbah: {qs(s['khutbah']) if s.get('khutbah') else 'nil'}, women: {str(bool(s.get('women'))).lower()})" for s in m["sessions"])
            kms.append(f"            EidMosque({q(m['name'])}, {opt_num(m.get('lat'))}, {opt_num(m.get('lng'))}, listOf({ks}), {q(m['note']) if m.get('note') else 'null'}),")
            sms.append(f"            EidMosque(name: {qs(m['name'])}, lat: {opt_num(m.get('lat'), True)}, lng: {opt_num(m.get('lng'), True)}, sessions: [{ss}], note: {qs(m['note']) if m.get('note') else 'nil'}),")
        kt += [f"        EidEvent({q(e['name'])}, {q(e['date'])}, {q(e['sourceUrl'])}, listOf(", *kms, "        )),"]
        sw += [f"        EidEvent(name: {qs(e['name'])}, date: {qs(e['date'])}, sourceURL: {qs(e['sourceUrl'])}, mosques: [", *sms, "        ]),"]
    kt += ["    )", "}", ""]
    sw += ["    ]", "}", ""]
    return "\n".join(kt), "\n".join(sw)


def main():
    kt, sw = build()
    if "--check" in sys.argv:
        bad = [p for p, t in ((KT, kt), (SW, sw)) if not os.path.exists(p) or open(p).read() != t]
        if bad:
            print("Out of date, run python3 tools/gen_masjid_extras.py:", *bad, sep="\n  ")
            return 1
        return 0
    open(KT, "w").write(kt)
    open(SW, "w").write(sw)
    return 0


if __name__ == "__main__":
    sys.exit(main())
